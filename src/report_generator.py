"""
Report Generator Module
Author: Akash Das
Project: Automated Resume Screening Tool

Responsible for generating standardized, downloadable candidate evaluation reports
in CSV and Excel (.xlsx) formats from Phase 9 ranked candidate records.

Ethical & Privacy Principles:
1. Strict Personal-Identifier Exclusion:
   Reports never export candidate names, email addresses, phone numbers,
   physical addresses, or personal contact headers. Only canonical Candidate IDs
   (e.g., 'CAND-001') and objective evaluation metrics are reported.
2. Complete Cohort Transparency (Zero Automated Rejection):
   Every successfully evaluated candidate—including those categorized as 'Low Match'—is
   fully represented in ranking reports. 'Low Match' is strictly an illustrative
   review prioritization aid, never an automated disqualification or rejection.
3. Educational Prototype Disclaimers:
   All reports explicitly document that scores reflect keyword coverage and TF-IDF
   text similarity against the benchmark job description, NOT scientifically validated
   measures of candidate competence, intelligence, or job performance.
"""

from datetime import datetime
import io
from pathlib import Path
from typing import List, Dict, Any, Optional, Union
import pandas as pd
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

# Standardized CSV & Excel Sheet 1 column names
RANKING_COLUMNS: List[str] = [
    "Rank",
    "Candidate ID",
    "Composite Match Score",
    "Required Skill Coverage",
    "Preferred Skill Coverage",
    "TF-IDF Cosine Similarity",
    "Human-Review Category",
]

# Standardized Excel Sheet 2 column names
DETAILS_COLUMNS: List[str] = [
    "Candidate ID",
    "Required Skills Matched",
    "Required Skills Missing",
    "Preferred Skills Matched",
    "Preferred Skills Missing",
    "Required Coverage",
    "Preferred Coverage",
    "TF-IDF Cosine Similarity",
    "Composite Match Score",
    "Human-Review Category",
]

DEFAULT_DISCLAIMER: str = (
    "This report was generated by the Automated Resume Screening Tool educational prototype. "
    "Scores and review categories represent keyword coverage and TF-IDF textual similarity "
    "against the benchmark job description, NOT scientifically validated measures of candidate "
    "competence, intelligence, or future job performance. Zero automated rejection has taken "
    "place; human recruiter review remains mandatory for all candidates."
)


def _validate_ranked_candidates_input(ranked_candidates: List[Dict[str, Any]]) -> None:
    """
    Validate that ranked_candidates is a list of dictionaries with required fields.

    Raises:
        TypeError: If input is not a list or items are not dictionaries.
        ValueError: If records are missing critical ranking fields.
    """
    if not isinstance(ranked_candidates, list):
        raise TypeError(
            f"ranked_candidates must be a list of dictionaries, got {type(ranked_candidates).__name__}."
        )

    for idx, record in enumerate(ranked_candidates):
        if not isinstance(record, dict):
            raise TypeError(f"Item at index {idx} is not a dictionary: {type(record).__name__}.")

        cid = record.get("candidate_id") or record.get("id")
        if not cid or not str(cid).strip():
            raise ValueError(f"Record at index {idx} is missing a valid 'candidate_id'.")

        if "composite_score" not in record and "Composite Match Score" not in record:
            raise ValueError(f"Record '{cid}' at index {idx} is missing 'composite_score'.")


def generate_ranking_dataframe(ranked_candidates: List[Dict[str, Any]]) -> pd.DataFrame:
    """
    Transform Phase 9 ranked candidate records into a standardized Pandas DataFrame
    suitable for CSV export and UI tabular presentation.

    Preserves exact ranking sequence, numerical precision, and excludes personal contact details.

    Args:
        ranked_candidates (List[Dict[str, Any]]): List of ranked candidate dictionaries from Phase 9.

    Returns:
        pd.DataFrame: Formatted DataFrame with columns:
            ['Rank', 'Candidate ID', 'Composite Match Score', 'Required Skill Coverage',
             'Preferred Skill Coverage', 'TF-IDF Cosine Similarity', 'Human-Review Category']

    Raises:
        TypeError: If ranked_candidates is not a list.
        ValueError: If candidate records are malformed.
    """
    _validate_ranked_candidates_input(ranked_candidates)

    if not ranked_candidates:
        return pd.DataFrame(columns=RANKING_COLUMNS)

    rows = []
    for idx, c in enumerate(ranked_candidates, start=1):
        rank = c.get("rank", idx)
        cid = str(c.get("candidate_id") or c.get("id", "")).strip()
        comp = float(c.get("composite_score", 0.0))

        # Handle required coverage
        if "required_skills" in c and isinstance(c["required_skills"], dict):
            req_cov = float(c["required_skills"].get("coverage", 0.0))
        else:
            req_cov = float(c.get("required_coverage", 0.0))

        # Handle preferred coverage
        if "preferred_skills" in c and isinstance(c["preferred_skills"], dict):
            pref_cov = float(c["preferred_skills"].get("coverage", 0.0))
        else:
            pref_cov = float(c.get("preferred_coverage", 0.0))

        # Handle similarity
        if "similarity" in c and isinstance(c["similarity"], dict):
            sim = float(c["similarity"].get("cosine_similarity", 0.0))
        else:
            sim = float(c.get("cosine_similarity", 0.0))

        category = str(c.get("review_category", "")).strip() or "Low Match"

        rows.append({
            "Rank": int(rank),
            "Candidate ID": cid,
            "Composite Match Score": comp,
            "Required Skill Coverage": req_cov,
            "Preferred Skill Coverage": pref_cov,
            "TF-IDF Cosine Similarity": sim,
            "Human-Review Category": category,
        })

    return pd.DataFrame(rows, columns=RANKING_COLUMNS)


def generate_details_dataframe(ranked_candidates: List[Dict[str, Any]]) -> pd.DataFrame:
    """
    Transform Phase 9 ranked candidate records into a detailed skill breakdown DataFrame
    for Sheet 2 of the Excel report.

    Args:
        ranked_candidates (List[Dict[str, Any]]): List of ranked candidate records.

    Returns:
        pd.DataFrame: Detailed results DataFrame.
    """
    _validate_ranked_candidates_input(ranked_candidates)

    if not ranked_candidates:
        return pd.DataFrame(columns=DETAILS_COLUMNS)

    rows = []
    for c in ranked_candidates:
        cid = str(c.get("candidate_id") or c.get("id", "")).strip()

        # Extract required skills lists
        req_data = c.get("required_skills", {}) if isinstance(c.get("required_skills"), dict) else {}
        matched_req = req_data.get("matched_names", [])
        missing_req = req_data.get("missing_names", [])
        req_cov = float(req_data.get("coverage", c.get("required_coverage", 0.0)))

        # Extract preferred skills lists
        pref_data = c.get("preferred_skills", {}) if isinstance(c.get("preferred_skills"), dict) else {}
        matched_pref = pref_data.get("matched_names", [])
        missing_pref = pref_data.get("missing_names", [])
        pref_cov = float(pref_data.get("coverage", c.get("preferred_coverage", 0.0)))

        # Extract similarity
        sim_data = c.get("similarity", {}) if isinstance(c.get("similarity"), dict) else {}
        sim = float(sim_data.get("cosine_similarity", c.get("cosine_similarity", 0.0)))

        comp = float(c.get("composite_score", 0.0))
        category = str(c.get("review_category", "")).strip() or "Low Match"

        rows.append({
            "Candidate ID": cid,
            "Required Skills Matched": ", ".join(matched_req) if matched_req else "None",
            "Required Skills Missing": ", ".join(missing_req) if missing_req else "None",
            "Preferred Skills Matched": ", ".join(matched_pref) if matched_pref else "None",
            "Preferred Skills Missing": ", ".join(missing_pref) if missing_pref else "None",
            "Required Coverage": req_cov,
            "Preferred Coverage": pref_cov,
            "TF-IDF Cosine Similarity": sim,
            "Composite Match Score": comp,
            "Human-Review Category": category,
        })

    return pd.DataFrame(rows, columns=DETAILS_COLUMNS)


def export_to_csv(
    ranked_candidates_or_df: Union[List[Dict[str, Any]], pd.DataFrame],
    output_path: Optional[Union[str, Path]] = None
) -> Union[Path, str]:
    """
    Export ranked candidate records to a standardized CSV format.

    Guarantees:
    - Ranking sequence is strictly preserved.
    - Personal contact details are never included.
    - Numerical values are preserved.
    - Supports saving directly to disk or returning an in-memory CSV string.

    Args:
        ranked_candidates_or_df (Union[List[Dict[str, Any]], pd.DataFrame]):
            Ranked candidate records list or pre-generated DataFrame.
        output_path (Optional[Union[str, Path]]): Destination file path.
            If None, returns the CSV content as a string.

    Returns:
        Union[Path, str]: The Path to the saved CSV file, or CSV string if output_path is None.
    """
    if isinstance(ranked_candidates_or_df, pd.DataFrame):
        df = ranked_candidates_or_df
    elif isinstance(ranked_candidates_or_df, list):
        df = generate_ranking_dataframe(ranked_candidates_or_df)
    else:
        raise TypeError(
            f"Expected List[Dict] or pd.DataFrame, got {type(ranked_candidates_or_df).__name__}."
        )

    csv_string = df.to_csv(index=False, encoding="utf-8")

    if output_path is not None:
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(csv_string, encoding="utf-8")
        return path

    return csv_string


def generate_csv_bytes(ranked_candidates: List[Dict[str, Any]]) -> bytes:
    """
    Generate in-memory UTF-8 encoded bytes for CSV download stream.
    Directly reusable by Phase 11 Streamlit st.download_button.

    Args:
        ranked_candidates (List[Dict[str, Any]]): List of ranked candidate records.

    Returns:
        bytes: Encoded CSV file content.
    """
    csv_str = export_to_csv(ranked_candidates, output_path=None)
    assert isinstance(csv_str, str)
    return csv_str.encode("utf-8")


def _apply_table_styling(
    ws: Any,
    header_fill_color: str = "1F4E78",
    header_text_color: str = "FFFFFF"
) -> None:
    """Apply professional styling, frozen header, auto-filter, and column widths to an openpyxl worksheet."""
    header_font = Font(name="Calibri", size=11, bold=True, color=header_text_color)
    header_fill = PatternFill(start_color=header_fill_color, end_color=header_fill_color, fill_type="solid")
    header_align = Alignment(horizontal="center", vertical="center", wrap_text=True)

    thin_border = Border(
        left=Side(style="thin", color="D9D9D9"),
        right=Side(style="thin", color="D9D9D9"),
        top=Side(style="thin", color="D9D9D9"),
        bottom=Side(style="thin", color="D9D9D9"),
    )

    # Style Header Row (Row 1)
    ws.row_dimensions[1].height = 28
    for col_idx in range(1, ws.max_column + 1):
        cell = ws.cell(row=1, column=col_idx)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = header_align

    # Style Data Cells
    for row_idx in range(2, ws.max_row + 1):
        ws.row_dimensions[row_idx].height = 20
        for col_idx in range(1, ws.max_column + 1):
            cell = ws.cell(row=row_idx, column=col_idx)
            cell.border = thin_border
            # Apply subtle zebra striping
            if row_idx % 2 == 1:
                cell.fill = PatternFill(start_color="F9FAFB", end_color="F9FAFB", fill_type="solid")

    # Freeze Header Row
    ws.freeze_panes = "A2"

    # Add Auto-Filter to header
    if ws.max_column > 0 and ws.max_row > 0:
        ws.auto_filter.ref = ws.dimensions

    # Auto-adjust column widths with safety margin
    for col in ws.columns:
        max_len = 0
        for cell in col:
            val_str = str(cell.value or "")
            if len(val_str) > max_len:
                max_len = len(val_str)
        col_letter = get_column_letter(col[0].column)
        ws.column_dimensions[col_letter].width = max(max_len + 4, 13)


def export_to_excel(
    ranked_candidates: List[Dict[str, Any]],
    output_path: Optional[Union[str, Path]] = None,
    metadata: Optional[Dict[str, Any]] = None
) -> Union[Path, bytes]:
    """
    Export ranked candidate evaluation records into a formatted, professional Excel (.xlsx) workbook.

    Sheets generated:
    1. 'Candidate Ranking': Main summary table with rank, score, coverages, similarity, review category.
    2. 'Detailed Results': Skill-level breakdown (matched vs missing skills) per candidate.
    3. 'Report Information': Project metadata, author, benchmark job description, scoring weights, and disclaimer.

    Formatting:
    - Bold headers with corporate fill.
    - Formatted number cells (2 decimal scores, percentage coverages, 4 decimal similarity).
    - Auto-filter on header rows.
    - Frozen header rows.
    - Preserves exact Phase 9 ranking order.

    Args:
        ranked_candidates (List[Dict[str, Any]]): List of Phase 9 ranked candidate records.
        output_path (Optional[Union[str, Path]]): File path to save. If None, returns workbook bytes.
        metadata (Optional[Dict[str, Any]]): Custom report metadata.

    Returns:
        Union[Path, bytes]: Saved file Path, or raw bytes if output_path is None.
    """
    _validate_ranked_candidates_input(ranked_candidates)

    wb = openpyxl.Workbook()

    # ----------------------------------------------------------------------
    # Sheet 1: Candidate Ranking
    # ----------------------------------------------------------------------
    ws_ranking = wb.active
    ws_ranking.title = "Candidate Ranking"

    ws_ranking.append(RANKING_COLUMNS)

    for idx, c in enumerate(ranked_candidates, start=1):
        rank = c.get("rank", idx)
        cid = str(c.get("candidate_id") or c.get("id", "")).strip()
        comp = float(c.get("composite_score", 0.0))

        if "required_skills" in c and isinstance(c["required_skills"], dict):
            req_cov = float(c["required_skills"].get("coverage", 0.0))
        else:
            req_cov = float(c.get("required_coverage", 0.0))

        if "preferred_skills" in c and isinstance(c["preferred_skills"], dict):
            pref_cov = float(c["preferred_skills"].get("coverage", 0.0))
        else:
            pref_cov = float(c.get("preferred_coverage", 0.0))

        if "similarity" in c and isinstance(c["similarity"], dict):
            sim = float(c["similarity"].get("cosine_similarity", 0.0))
        else:
            sim = float(c.get("cosine_similarity", 0.0))

        category = str(c.get("review_category", "")).strip() or "Low Match"

        row = [rank, cid, comp, req_cov, pref_cov, sim, category]
        ws_ranking.append(row)

        row_num = ws_ranking.max_row
        # Number formats:
        # Col 1: Rank (center)
        ws_ranking.cell(row=row_num, column=1).alignment = Alignment(horizontal="center")
        # Col 2: Candidate ID (center)
        ws_ranking.cell(row=row_num, column=2).alignment = Alignment(horizontal="center")
        # Col 3: Composite Score (0.00)
        c_comp = ws_ranking.cell(row=row_num, column=3)
        c_comp.number_format = "0.00"
        c_comp.alignment = Alignment(horizontal="right")
        # Col 4: Required Skill Coverage (0.0%)
        c_req = ws_ranking.cell(row=row_num, column=4)
        c_req.number_format = "0.0%"
        c_req.alignment = Alignment(horizontal="right")
        # Col 5: Preferred Skill Coverage (0.0%)
        c_pref = ws_ranking.cell(row=row_num, column=5)
        c_pref.number_format = "0.0%"
        c_pref.alignment = Alignment(horizontal="right")
        # Col 6: TF-IDF Cosine Similarity (0.0000)
        c_sim = ws_ranking.cell(row=row_num, column=6)
        c_sim.number_format = "0.0000"
        c_sim.alignment = Alignment(horizontal="right")
        # Col 7: Category (center)
        ws_ranking.cell(row=row_num, column=7).alignment = Alignment(horizontal="center")

    _apply_table_styling(ws_ranking, header_fill_color="1F4E78")

    # ----------------------------------------------------------------------
    # Sheet 2: Detailed Results
    # ----------------------------------------------------------------------
    ws_details = wb.create_sheet(title="Detailed Results")
    ws_details.append(DETAILS_COLUMNS)

    for c in ranked_candidates:
        cid = str(c.get("candidate_id") or c.get("id", "")).strip()

        req_data = c.get("required_skills", {}) if isinstance(c.get("required_skills"), dict) else {}
        matched_req = req_data.get("matched_names", [])
        missing_req = req_data.get("missing_names", [])
        req_cov = float(req_data.get("coverage", c.get("required_coverage", 0.0)))

        pref_data = c.get("preferred_skills", {}) if isinstance(c.get("preferred_skills"), dict) else {}
        matched_pref = pref_data.get("matched_names", [])
        missing_pref = pref_data.get("missing_names", [])
        pref_cov = float(pref_data.get("coverage", c.get("preferred_coverage", 0.0)))

        sim_data = c.get("similarity", {}) if isinstance(c.get("similarity"), dict) else {}
        sim = float(sim_data.get("cosine_similarity", c.get("cosine_similarity", 0.0)))

        comp = float(c.get("composite_score", 0.0))
        category = str(c.get("review_category", "")).strip() or "Low Match"

        row = [
            cid,
            ", ".join(matched_req) if matched_req else "None",
            ", ".join(missing_req) if missing_req else "None",
            ", ".join(matched_pref) if matched_pref else "None",
            ", ".join(missing_pref) if missing_pref else "None",
            req_cov,
            pref_cov,
            sim,
            comp,
            category,
        ]
        ws_details.append(row)

        row_num = ws_details.max_row
        ws_details.cell(row=row_num, column=1).alignment = Alignment(horizontal="center")
        # Number formats
        c_rcov = ws_details.cell(row=row_num, column=6)
        c_rcov.number_format = "0.0%"
        c_rcov.alignment = Alignment(horizontal="right")

        c_pcov = ws_details.cell(row=row_num, column=7)
        c_pcov.number_format = "0.0%"
        c_pcov.alignment = Alignment(horizontal="right")

        c_sim2 = ws_details.cell(row=row_num, column=8)
        c_sim2.number_format = "0.0000"
        c_sim2.alignment = Alignment(horizontal="right")

        c_comp2 = ws_details.cell(row=row_num, column=9)
        c_comp2.number_format = "0.00"
        c_comp2.alignment = Alignment(horizontal="right")

        ws_details.cell(row=row_num, column=10).alignment = Alignment(horizontal="center")

    _apply_table_styling(ws_details, header_fill_color="2F5597")

    # ----------------------------------------------------------------------
    # Sheet 3: Report Information
    # ----------------------------------------------------------------------
    ws_info = wb.create_sheet(title="Report Information")

    meta = metadata or {}
    job_name = meta.get("job_title", "Junior Data Analyst")
    report_date = meta.get("report_date", datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
    weights_desc = meta.get("weights_desc", "70% required skills, 10% preferred skills, 20% TF-IDF similarity")

    info_rows = [
        ("PROJECT METADATA", ""),
        ("Project Name", "Automated Resume Screening Tool"),
        ("Author", "Akash Das"),
        ("Benchmark Job Role", job_name),
        ("Scoring Weights", weights_desc),
        ("Report Generation Timestamp", str(report_date)),
        ("Total Candidates Evaluated", len(ranked_candidates)),
        ("", ""),
        ("REVIEW CATEGORY SUMMARY", ""),
        ("High Match (Score >= 70)", sum(1 for c in ranked_candidates if c.get("review_category") == "High Match")),
        ("Moderate Match (40 <= Score < 70)", sum(1 for c in ranked_candidates if c.get("review_category") == "Moderate Match")),
        ("Low Match (Score < 40)", sum(1 for c in ranked_candidates if c.get("review_category") == "Low Match")),
        ("", ""),
        ("EDUCATIONAL PROTOTYPE DISCLAIMER", ""),
        ("Notice", DEFAULT_DISCLAIMER),
    ]

    for item in info_rows:
        ws_info.append([item[0], item[1]])

    # Format Sheet 3
    section_header_fill = PatternFill(start_color="D9E1F2", end_color="D9E1F2", fill_type="solid")
    section_header_font = Font(name="Calibri", size=11, bold=True, color="1F4E78")

    for row_idx in range(1, ws_info.max_row + 1):
        cell_a = ws_info.cell(row=row_idx, column=1)
        cell_b = ws_info.cell(row=row_idx, column=2)

        if cell_a.value in {"PROJECT METADATA", "REVIEW CATEGORY SUMMARY", "EDUCATIONAL PROTOTYPE DISCLAIMER"}:
            cell_a.font = section_header_font
            cell_a.fill = section_header_fill
            cell_b.fill = section_header_fill
            ws_info.row_dimensions[row_idx].height = 24
        elif cell_a.value:
            cell_a.font = Font(name="Calibri", size=10, bold=True)
            cell_b.font = Font(name="Calibri", size=10)
            ws_info.row_dimensions[row_idx].height = 20

    # Disclaimer text wrapping
    disclaimer_cell = ws_info.cell(row=15, column=2)
    disclaimer_cell.alignment = Alignment(wrap_text=True, vertical="top")
    ws_info.row_dimensions[15].height = 65

    ws_info.column_dimensions["A"].width = 32
    ws_info.column_dimensions["B"].width = 75

    # ----------------------------------------------------------------------
    # Output Dispatch
    # ----------------------------------------------------------------------
    if output_path is not None:
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        wb.save(str(path))
        return path

    buffer = io.BytesIO()
    wb.save(buffer)
    buffer.seek(0)
    return buffer.getvalue()


def generate_excel_bytes(
    ranked_candidates: List[Dict[str, Any]],
    metadata: Optional[Dict[str, Any]] = None
) -> bytes:
    """
    Generate in-memory bytes for Excel (.xlsx) download stream.
    Directly reusable by Phase 11 Streamlit st.download_button.

    Args:
        ranked_candidates (List[Dict[str, Any]]): List of ranked candidate records.
        metadata (Optional[Dict[str, Any]]): Custom report metadata.

    Returns:
        bytes: Encoded workbook bytes.
    """
    res = export_to_excel(ranked_candidates, output_path=None, metadata=metadata)
    assert isinstance(res, bytes)
    return res
